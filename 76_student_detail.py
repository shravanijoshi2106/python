class Student:
    def __init__(self, name, age, marks):
        self.name = name
        self.age = age
        self.marks = marks

# Create an object
s1 = Student("shravani Joshi", 21, 95)

# Display student details
print("Student Name:", s1.name)
print("Student Age:", s1.age)
print("Student Marks:", s1.marks)